#!/usr/bin/env python
"""Write ``src/lib/connectors.generated.ts`` from the connector list (IN-11).

    uv run python scripts/gen_connectors.py

``tests/unit/test_connector_list.py`` renders the file again and fails when
the committed copy is stale.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SRC = REPO_ROOT / "packages/acb_common/acb_common/connector_list.json"
OUT = REPO_ROOT / "workbench/control_plane/src/lib/connectors.generated.ts"


def render_ts() -> str:
    rows = json.loads(SRC.read_text(encoding="utf-8"))["rows"]
    body = json.dumps(rows, indent=2, ensure_ascii=False)
    return (
        "// AUTO-GENERATED by scripts/gen_connectors.py. Do not edit by hand.\n"
        "// Source: packages/acb_common/acb_common/connector_list.json\n"
        "// Regenerate: uv run python scripts/gen_connectors.py\n"
        'import type { Connector } from "@/lib/connectors";\n\n'
        f"export const CONNECTOR_ROWS: readonly Connector[] = {body};\n"
    )


if __name__ == "__main__":
    OUT.write_text(render_ts(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}", file=sys.stderr)
