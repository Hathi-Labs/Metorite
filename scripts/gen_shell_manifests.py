#!/usr/bin/env python
"""Regenerate the command bar's jobs for TypeScript from the shell manifests.

Run after editing a file under ``packages/acb_common/acb_common/app_manifests/shell``:

    uv run python scripts/gen_shell_manifests.py

It writes ``workbench/control_plane/src/lib/shell/jobs.generated.ts`` and
``vocabulary.generated.ts`` (the pane links, preset ids and card keys, PKG-2) and
``gates.generated.ts`` (``ALSO_SERVES`` in PKG-3a, ``HREF_FEATURES`` and
``ALWAYS_ALLOWED`` in PKG-3b).
``anchors.generated.ts`` (the anchors a guide may ring, GD-1).
``tests/unit/test_shell_manifests.py`` renders the file again and fails if the
committed copy is stale (WS-PKG, PKG-1; ``project-docs/specs/package_host.md`` §4).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT = REPO_ROOT / "workbench" / "control_plane" / "src" / "lib" / "shell" / "jobs.generated.ts"

VOCAB_OUT = OUT.with_name("vocabulary.generated.ts")
GATES_OUT = OUT.with_name("gates.generated.ts")
ANCHORS_OUT = OUT.with_name("anchors.generated.ts")
GUIDES_OUT = OUT.with_name("guides.generated.ts")

HEADER = """\
// AUTO-GENERATED by scripts/gen_shell_manifests.py. Do not edit by hand.
// Source: packages/acb_common/acb_common/app_manifests/shell/*.json
// Regenerate: uv run python scripts/gen_shell_manifests.py
import type { ShellJob } from "@/lib/shell/registry";

export const GENERATED_JOBS: readonly ShellJob[] = [
"""


def _q(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_ts(jobs) -> str:
    """The text of ``jobs.generated.ts`` for these ``JobSpec`` values, LF only."""
    out = [HEADER]
    for j in jobs:
        out.append("  {\n")
        if j.note:
            out.append(f"    // {j.note}\n")
        out.append(f"    id: {_q(j.id)},\n")
        out.append(f"    label: {_q(j.label)},\n")
        out.append(f"    words: [{', '.join(_q(w) for w in j.words)}],\n")
        out.append(f"    app: {_q(j.app)},\n")
        out.append(f"    href: {_q(j.href)},\n")
        out.append(f"    icon: {_q(j.icon)},\n")
        if j.bar_feature:
            out.append(f"    feature: {_q(j.bar_feature)},\n")
        if j.fallback_feature:
            out.append(
                f"    fallback: {{ feature: {_q(j.fallback_feature)}, href: {_q(j.fallback_href)} }},\n"
            )
        out.append("  },\n")
    out.append("];\n")
    return "".join(out)


def render_vocabulary_ts(vocab) -> str:
    """The text of ``vocabulary.generated.ts`` for a ``Vocabulary``, LF only."""
    out = [
        "// AUTO-GENERATED by scripts/gen_shell_manifests.py. Do not edit by hand.\n",
        "// Source: packages/acb_common/acb_common/app_manifests/shell/*.json\n",
        "// Regenerate: uv run python scripts/gen_shell_manifests.py\n",
    ]
    for name, values in (
        ("GENERATED_PANE_HREFS", vocab.panes),
        ("GENERATED_PRESET_IDS", vocab.presets),
        ("GENERATED_CARD_KEYS", vocab.cards),
    ):
        out.append(f"\nexport const {name}: readonly string[] = [\n")
        out.extend(f"  {_q(v)},\n" for v in values)
        out.append("];\n")
    return "".join(out)


def render_gates_ts(gates) -> str:
    """The text of ``gates.generated.ts`` for a ``Gates``, LF only."""
    nl = "\n"
    out = [
        "// AUTO-GENERATED by scripts/gen_shell_manifests.py. Do not edit by hand." + nl,
        "// Source: packages/acb_common/acb_common/app_manifests/shell/*.json" + nl,
        "// Regenerate: uv run python scripts/gen_shell_manifests.py" + nl,
        nl + "export const GENERATED_ALSO_SERVES: Readonly<Record<string, readonly string[]>> = {" + nl,
    ]
    for agent, hrefs in gates.also_serves.items():
        out.append(f"  {_q(agent)}: [{', '.join(_q(h) for h in hrefs)}]," + nl)
    out.append("};" + nl)
    out.append(
        nl + "export const GENERATED_HREF_FEATURES: ReadonlyArray<readonly [string, string]> = [" + nl
    )
    for href, feature in gates.href_features:
        out.append(f"  [{_q(href)}, {_q(feature)}]," + nl)
    out.append("];" + nl)
    out.append(nl + "export const GENERATED_ALWAYS_ALLOWED: readonly string[] = [" + nl)
    for href in gates.always_allowed:
        out.append(f"  {_q(href)}," + nl)
    out.append("];" + nl)
    return "".join(out)


def render_anchors_ts(anchors) -> str:
    """The text of ``anchors.generated.ts`` for these ``AnchorSpec`` values, LF only (GD-1)."""
    nl = "\n"
    out = [
        "// AUTO-GENERATED by scripts/gen_shell_manifests.py. Do not edit by hand." + nl,
        "// Source: packages/acb_common/acb_common/app_manifests/shell/*.json" + nl,
        "// Regenerate: uv run python scripts/gen_shell_manifests.py" + nl,
        nl + "export type GuideAnchor = {" + nl,
        "  id: GuideAnchorId;" + nl,
        "  label: string;" + nl,
        "  route: string;" + nl,
        "  does: string;" + nl,
        "};" + nl,
        nl + "export type GuideAnchorId =" + nl,
    ]
    ids = [a.full_id for a in anchors]
    out.append(("".join(f"  | {_q(i)}" + nl for i in ids)).rstrip(nl) + ";" + nl if ids else "  never;" + nl)
    out.append(nl + "export const GENERATED_ANCHORS: readonly GuideAnchor[] = [" + nl)
    for a in anchors:
        out.append("  {" + nl)
        out.append(f"    id: {_q(a.full_id)}," + nl)
        out.append(f"    label: {_q(a.label)}," + nl)
        out.append(f"    route: {_q(a.route)}," + nl)
        out.append(f"    does: {_q(a.does)}," + nl)
        out.append("  }," + nl)
    out.append("];" + nl)
    return "".join(out)


_GUIDES_TYPES = """
export type GuideStep =
  | { kind: "open"; say: string; path: string }
  | { kind: "point"; say: string; anchor: GuideAnchorId }
  | { kind: "fill"; say: string; form: string; values: Readonly<Record<string, string>> }
  | { kind: "say"; say: string };

export type Guide = {
  id: string;
  app: string;
  feature: string | null;
  adminOnly: boolean;
  title: string;
  asks: readonly string[];
  steps: readonly GuideStep[];
  doTool: string | null;
};
"""


def _step_ts(step) -> str:
    parts = [f"kind: {_q(step.kind)}", f"say: {_q(step.say)}"]
    if step.kind == "open":
        parts.append(f"path: {_q(step.path)}")
    elif step.kind == "point":
        parts.append(f"anchor: {_q(step.anchor)}")
    elif step.kind == "fill":
        values = ", ".join(f"{_q(k)}: {_q(v)}" for k, v in step.values.items())
        parts += [f"form: {_q(step.form)}", f"values: {{ {values} }}"]
    return "      { " + ", ".join(parts) + " },\n"


def render_guides_ts(guides) -> str:
    """The text of ``guides.generated.ts`` for these ``Guide`` values, LF only (GD-3)."""
    out = [
        "// AUTO-GENERATED by scripts/gen_shell_manifests.py. Do not edit by hand.\n",
        "// Source: packages/acb_common/acb_common/app_manifests/guides/*.json\n",
        "// Regenerate: uv run python scripts/gen_shell_manifests.py\n",
        'import type { GuideAnchorId } from "@/lib/shell/anchors.generated";\n',
        _GUIDES_TYPES,
        "\nexport const GENERATED_GUIDES: readonly Guide[] = [\n",
    ]
    for g in guides:
        out.append("  {\n")
        out.append(f"    id: {_q(g.id)},\n")
        out.append(f"    app: {_q(g.app)},\n")
        out.append(f"    feature: {_q(g.feature) if g.feature else 'null'},\n")
        out.append(f"    adminOnly: {'true' if g.admin_only else 'false'},\n")
        out.append(f"    title: {_q(g.title)},\n")
        out.append(f"    asks: [{', '.join(_q(a) for a in g.asks)}],\n")
        out.append("    steps: [\n")
        out.extend(_step_ts(s) for s in g.steps)
        out.append("    ],\n")
        out.append(f"    doTool: {_q(g.do_tool) if g.do_tool else 'null'},\n")
        out.append("  },\n")
    out.append("];\n")
    return "".join(out)


def main() -> int:
    sys.path.insert(0, str(REPO_ROOT / "packages" / "acb_common"))
    from acb_common.app_manifests.guide_manifest import load_guides
    from acb_common.app_manifests.shell_manifest import (
        load_anchors,
        load_gates,
        load_jobs,
        load_vocabulary,
    )

    jobs = load_jobs()
    OUT.write_text(render_ts(jobs), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO_ROOT)} ({len(jobs)} jobs)")
    vocab = load_vocabulary()
    VOCAB_OUT.write_text(render_vocabulary_ts(vocab), encoding="utf-8", newline="\n")
    print(
        f"wrote {VOCAB_OUT.relative_to(REPO_ROOT)} "
        f"({len(vocab.panes)} panes, {len(vocab.presets)} presets, {len(vocab.cards)} cards)"
    )
    gates = load_gates()
    GATES_OUT.write_text(render_gates_ts(gates), encoding="utf-8", newline="\n")
    print(
        f"wrote {GATES_OUT.relative_to(REPO_ROOT)} "
        f"({len(gates.also_serves)} agent, {len(gates.href_features)} gated routes, "
        f"{len(gates.always_allowed)} always-allowed)"
    )
    anchors = load_anchors()
    ANCHORS_OUT.write_text(render_anchors_ts(anchors), encoding="utf-8", newline="\n")
    print(f"wrote {ANCHORS_OUT.relative_to(REPO_ROOT)} ({len(anchors)} anchors)")
    guides = load_guides()
    GUIDES_OUT.write_text(render_guides_ts(guides), encoding="utf-8", newline="\n")
    print(f"wrote {GUIDES_OUT.relative_to(REPO_ROOT)} ({len(guides)} guides)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
