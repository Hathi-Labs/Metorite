import { open, newChat, send, both, BASE, forwardApprove } from "./live.mjs";
const TAG = process.argv[2] || "on";
const TID = "878c88d3-2be9-4fc1-9183-10285bcfef75";
const OUT = "../../.demo/shots/precond-" + TAG;
const api = async (m, p, b) => { const r = await fetch(BASE + "/api" + p, { method: m, headers: { "content-type": "application/json" }, body: b ? JSON.stringify(b) : undefined }); return r.ok ? r.json() : { error: r.status, text: await r.text() }; };
await api("PATCH", "/projects/tasks/" + TID, { title: "Final price for the café bar stools", description: "Final quote expected on Monday." });
const before = await api("GET", "/projects/tasks/" + TID);
console.log("before", before.description, before.updated_at);
const { browser, page } = await open();
page.on("request", (q) => { if (q.method() !== "GET") console.log("REQ", q.method(), q.url().replace(BASE, ""), (q.postData() || "").slice(0, 160)); });
await forwardApprove(page);
const box = await newChat(page);
await page.getByRole("button", { name: "New chat", exact: true }).first().click();
await page.waitForTimeout(1500);
await send(page, box, "Please add a note to the bar stools task: ask the vendor for a 10% discount.");
await page.getByRole("button", { name: "Approve", exact: true }).waitFor({ timeout: 60000 });
await page.waitForTimeout(800);
await both(page, OUT + "-1-card-waits");
const other = await api("PATCH", "/projects/tasks/" + TID, { description: "Meera: get three quotes before we pay any deposit." });
console.log("other member edit", other.description, other.updated_at);
await page.waitForTimeout(800);
await both(page, OUT + "-2-after-other-edit");
await page.getByRole("button", { name: "Approve", exact: true }).click();
await page.waitForTimeout(40000);
await both(page, OUT + "-3-after-approve");
const after = await api("GET", "/projects/tasks/" + TID);
console.log("after", after.description, after.updated_at);
console.log("BODY:", (await page.locator("main, body").first().innerText()).split("\n").slice(-25).join(" | ").slice(0, 1500));
await browser.close();
