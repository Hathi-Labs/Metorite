import { open, newChat, send, both, forwardApprove } from "./live.mjs";
const TAG = process.argv[2] || "on";
const OUT = "../../.demo/shots/revise-" + TAG;
const { browser, page } = await open();
await forwardApprove(page);
page.on("request", (q) => { if (q.method() !== "GET" && /agent|steer/.test(q.url())) console.log("REQ", q.method(), q.url().replace("http://localhost:3423", ""), (q.postData() || "").slice(0, 200)); });
const box = await newChat(page);
await page.getByRole("button", { name: "New chat", exact: true }).first().click();
await page.waitForTimeout(1500);
await send(page, box, "Please draft an email to the vendor about the bar stools.");
await page.getByText(/Drafts|Save draft|Approve/).first().waitFor({ timeout: 60000 });
await page.waitForTimeout(1500);
await both(page, OUT + "-1-card-waits");
await box.fill("Make it shorter and more formal.");
await page.getByRole("button", { name: /^(Send|Steer|Add)/ }).last().click();
await page.waitForTimeout(25000);
await both(page, OUT + "-2-after-message");
console.log("BODY:", (await page.locator("body").innerText()).split("\n").filter(Boolean).slice(-30).join(" | ").slice(0, 1800));
await browser.close();
